let CURRENT_LANG = (localStorage_safe_get() || detectLang());

function localStorage_safe_get() {
  try { return localStorage.getItem("fp_lang"); } catch (e) { return null; }
}
function localStorage_safe_set(v) {
  try { localStorage.setItem("fp_lang", v); } catch (e) {}
}
function detectLang() {
  const nav = (navigator.language || "ru").toLowerCase();
  if (nav.startsWith("en")) return "en";
  if (nav.startsWith("ro")) return "ro";
  if (nav.startsWith("uk")) return "uk";
  return "ru";
}
